const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
const textNodes = [];
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest('script, style, .languages')) continue;
  const key = node.textContent.trim();
  if (translations[key]) textNodes.push({node, original: node.textContent, key});
}
const attributes = [];
document.querySelectorAll('[alt], [aria-label]').forEach(element => {
  for (const name of ['alt', 'aria-label']) {
    const original = element.getAttribute(name);
    if (translations[original]) attributes.push({element, name, original});
  }
});
function setLanguage(language) {
  const english = language === 'en';
  document.documentElement.lang = english ? 'en' : 'zh-CN';
  textNodes.forEach(({node, original, key}) => {
    node.textContent = english ? original.replace(key, translations[key]) : original;
  });
  attributes.forEach(({element, name, original}) => {
    element.setAttribute(name, english ? translations[original] : original);
  });
  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
  try { localStorage.setItem('site-language', language); } catch (_) {}
}
document.querySelectorAll('[data-language]').forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});
let preferred = 'zh';
try { preferred = localStorage.getItem('site-language') || 'zh'; } catch (_) {}
setLanguage(preferred === 'en' ? 'en' : 'zh');
